"""
carrier_jump_test.py -- Part I events as the clock, a carrier-mediated jump as the population flow.
Does the combination give a population martingale, absorption, and Born-weighted records?

STATE AND JUMP LAW (fixed before running)
  Channel populations x on the simplex, n = 3, x(0) = (0.5, 0.3, 0.2).
  An event on channel k with sign s = +1 or -1 changes the populations by

      x  ->  x + s * EPS * x_k * (e_k - x)          (EPS = 0.3)

  i.e. channel k exchanges with the shared carrier and the carrier redistributes over all
  channels in proportion to their populations (carrier-mediated; no channel-to-channel term).
  Properties (derived): populations stay nonnegative and sum to 1; every vertex is a fixed point;
  given the channel k, E[dx | F] = EPS * x_k (e_k - x) * E[s | F, k].
  So x is a martingale  <=>  E[s | F, k] = 0 for every channel with x_k > 0.
  The whole question is therefore whether the SIGN supplied by the substrate is conditionally fair.

RECORD
  First passage: the record is the first channel with x_k >= H = 0.999 (Part III, Prop. 3:
  |P - x(0)| <= (1-H)/H = 0.001 if x is a martingale). Runs not absorbed within MAX_EVENTS
  are reported as unresolved.

ARMS (event clock and sign source)
  POS        positive control: Poisson events, channel uniform, sign an independent fair coin.
  REV-m      Part I velocity reversals (telegraph process, v4): N = 3m defects, defect i belongs
             to channel i mod 3; each reversal of defect i is an event on its channel, with
             sign = the defect's NEW velocity direction. m = 1 and m = 4.
  REV-1-shuf the REV-1 sign sequence of each run (first 5000 events), randomly permuted before
             use (keeps the number of + and - signs, destroys their order).
  CROSS      Part I ring crossings (v4 dynamics: ring L = 5, speed 1, reversal rate 1, dt = 0.02,
             N = 3 defects, one per channel): when defect a overtakes defect b, channel(a) gets
             s = +1 and channel(b) gets s = -1, applied in that order.
  NEG        negative control: the populations are |psi_k|^2 and each Poisson event rotates psi by
             +-PHI (fair sign) in a uniformly chosen coordinate plane (Part III, Sec. 5.3).

MEASUREMENTS
  M1  Sign memory: E[s | previous sign on the same channel = +1] and [= -1], with 99% CIs.
      Fair signs require both to be 0.
  M2  Absorbed fraction, and the Born test on records: upper 99% bootstrap bound of
      TV(P, x(0)) <= EPS_TV = 0.02 (computed only if >= 99% of runs are absorbed).
  M3  For NEG: mean final populations, for reference.
  Note: the record is a FIRST PASSAGE. "absorbed" below means "reached H"; it does not mean the
  vertex is a trap. Born-weighted first passage requires the martingale (Part III, Prop. 3).

PREDICTIONS (written before running)
  P1  POS: >= 99% absorbed and Born passes.              (control; failure voids the run)
  P2  NEG: records NOT Born: lower 99% bound of TV(P, x(0)) > EPS_TV. (control; failure voids
      the run). [Revised after a --quick code check, before any production run: v0 predicted
      "< 1% absorbed", which is wrong for a first-passage record. A mixing process reaches
      x_k >= H eventually; what distinguishes it is that its records are not Born-weighted.]
  P3  REV-1: E[s | s_prev] = -s_prev exactly (a defect's reversals alternate in direction),
      so the sign is NOT conditionally fair and x is not a martingale under the filtration
      generated by the populations themselves.
  P4  REV-1-shuf: Born passes (if REV-1 fails, the failure is due to sign order, not sign counts).
  No prediction is made for whether REV-1, REV-4 or CROSS give Born records.

Usage: python carrier_jump_test.py [--quick] [--hash]
"""
import sys, json, math, hashlib, pathlib, time
import numpy as np

QUICK = "--quick" in sys.argv
TRIALS = 2000 if QUICK else 10000
X0 = np.array([0.5, 0.3, 0.2]); NCH = 3
EPS, H, EPS_TV, CONF, N_BOOT = 0.3, 0.999, 0.02, 0.99, 2000
MAX_EVENTS = 200000
PHI = 0.3
SHUF_LEN = 5000          # pre-generated events per run for the shuffled arm (POS needs < 1000)
SEED = 20261103
Z99 = 2.5758


# ------------------------------------------------------------------ jump and record
def jump(x, k, s):
    """x: (R, 3); k, s: (R,). Carrier-mediated exchange on channel k with sign s."""
    xk = x[np.arange(len(k)), k]
    e = np.zeros_like(x); e[np.arange(len(k)), k] = 1.0
    x = x + (s * EPS * xk)[:, None] * (e - x)
    x = np.clip(x, 0.0, None)
    return x / x.sum(1, keepdims=True)


class Memory:
    """Counts (previous sign on channel, current sign) pairs."""
    def __init__(self, R):
        self.prev = np.zeros((R, NCH), int); self.c = np.zeros((2, 2), int)

    def add(self, rows, k, s):
        p = self.prev[rows, k]; ok = p != 0
        for a in (0, 1):
            for b in (0, 1):
                self.c[a, b] += int(np.sum(ok & (p == (1 if a else -1)) & (s == (1 if b else -1))))
        self.prev[rows, k] = s

    def summary(self):
        out = {}
        for a, lab in ((1, "+1"), (0, "-1")):
            n = self.c[a].sum()
            if n == 0:
                out[lab] = (float("nan"), float("nan"), float("nan"), 0); continue
            m = (self.c[a, 1] - self.c[a, 0]) / n
            se = math.sqrt(max(1 - m * m, 1e-12) / n)
            out[lab] = (m, m - Z99 * se, m + Z99 * se, int(n))
        return out


def finish(x, done, rec):
    """Mark runs that reached the first-passage threshold."""
    hit = (~done) & (x.max(1) >= H)
    rec[hit] = x[hit].argmax(1); done |= hit
    return done


# ------------------------------------------------------------------ event-driven arms
def run_events(rng, kind, m=1, shuffle=False):
    R = TRIALS; N = NCH * m
    x = np.tile(X0, (R, 1)); done = np.zeros(R, bool); rec = np.full(R, -1)
    mem = Memory(R)
    v = rng.choice([-1, 1], (R, N))                       # telegraph velocity directions
    if kind == "REV" and shuffle:
        # pre-generate the whole REV sign sequence per run, then permute it
        defects = rng.integers(0, N, (R, SHUF_LEN)).astype(np.int16)
        signs = np.empty((R, SHUF_LEN), np.int8); vv = v.copy()
        for t in range(SHUF_LEN):
            d = defects[:, t]; vv[np.arange(R), d] *= -1; signs[:, t] = vv[np.arange(R), d]
        for r in range(R):
            rng.shuffle(signs[r])
    for t in range(SHUF_LEN if shuffle else MAX_EVENTS):
        rows = np.flatnonzero(~done)
        if rows.size == 0:
            break
        if kind == "POS":
            k = rng.integers(0, NCH, rows.size); s = rng.choice([-1, 1], rows.size)
        elif kind == "REV" and not shuffle:
            d = rng.integers(0, N, rows.size)              # next reversing defect (equal rates)
            v[rows, d] *= -1; s = v[rows, d]; k = d % NCH
        elif kind == "REV" and shuffle:
            d = defects[rows, t].astype(int); s = signs[rows, t].astype(int); k = d % NCH
        mem.add(rows, k, s)
        x[rows] = jump(x[rows], k, s)
        done = finish(x, done, rec)
    return rec, done, mem, x


def run_cross(rng, L=5.0, c=1.0, gamma=1.0, dt=0.02, max_steps=None):
    """Part I v4 ring dynamics, N = 3 (one defect per channel); crossings are the events."""
    R = TRIALS; N = NCH
    max_steps = max_steps or (300000 if not QUICK else 150000)
    X = rng.uniform(0, L, (R, N)); V = c * rng.choice([-1, 1], (R, N))
    iu = [(0, 1), (0, 2), (1, 2)]
    fl = np.stack([np.floor((X[:, i] - X[:, j]) / L) for i, j in iu], 1)
    x = np.tile(X0, (R, 1)); done = np.zeros(R, bool); rec = np.full(R, -1); mem = Memory(R)
    events = np.zeros(R, int)
    for step in range(max_steps):
        live = ~done
        if not live.any():
            break
        X[live] += V[live] * dt
        flip = live[:, None] & (rng.random((R, N)) < gamma * dt)
        V[flip] *= -1
        nfl = np.stack([np.floor((X[:, i] - X[:, j]) / L) for i, j in iu], 1)
        ch = (nfl != fl) & live[:, None]
        if ch.any():
            for p, (i, j) in enumerate(iu):
                rows = np.flatnonzero(ch[:, p])
                if rows.size == 0:
                    continue
                up = nfl[rows, p] > fl[rows, p]           # X_i - X_j increased through a multiple of L
                a = np.where(up, i, j); b = np.where(up, j, i)   # a overtook b
                for kk, ss in ((a, 1), (b, -1)):
                    sv = np.full(rows.size, ss)
                    mem.add(rows, kk, sv)
                    x[rows] = jump(x[rows], kk, sv)
                events[rows] += 2
                done = finish(x, done, rec)
        fl = nfl
    return rec, done, mem, x, events


def run_neg(rng):
    R = TRIALS
    psi = np.tile(np.sqrt(X0), (R, 1)); done = np.zeros(R, bool); rec = np.full(R, -1)
    planes = [(0, 1), (0, 2), (1, 2)]
    for t in range(20000):
        p = rng.integers(0, 3, R); s = rng.choice([-1, 1], R)
        c, sn = np.cos(s * PHI), np.sin(s * PHI)
        i = np.array([planes[q][0] for q in p]); j = np.array([planes[q][1] for q in p])
        a, b = psi[np.arange(R), i].copy(), psi[np.arange(R), j].copy()
        psi[np.arange(R), i] = c * a - sn * b; psi[np.arange(R), j] = sn * a + c * b
        x = psi ** 2
        done = finish(x, done, rec)
    return rec, done, psi ** 2


# ------------------------------------------------------------------ statistics
def born(rec, rng):
    ok = rec >= 0; cnt = np.bincount(rec[ok], minlength=NCH); nr = cnt.sum()
    if nr == 0:
        return None
    p = cnt / nr
    boot = rng.multinomial(nr, p, size=N_BOOT) / nr
    tvs = 0.5 * np.abs(boot - X0).sum(1)
    lo, hi = np.percentile(tvs, [100 * (1 - CONF) / 2, 100 * (1 + CONF) / 2])
    return dict(P=p.round(4).tolist(), tv=float(0.5 * np.abs(p - X0).sum()), tv_lo=float(lo), tv_hi=float(hi))


def main():
    here = pathlib.Path(__file__).resolve()
    digest = hashlib.sha256(here.read_bytes()).hexdigest()
    if "--hash" in sys.argv:
        print(digest); return
    t0 = time.time()
    ss = np.random.SeedSequence(SEED).spawn(10)
    print("=" * 100)
    print(f"Carrier-jump test | trials={TRIALS} EPS={EPS} H={H} x0={X0.tolist()} {'(QUICK)' if QUICK else ''}\n"
          f"script sha256 {digest}")
    print("=" * 100)
    results = {}

    def report(name, rec, done, mem, extra=""):
        b = born(rec, np.random.default_rng(ss[9]))
        absorbed = float(done.mean())
        ms = mem.summary() if mem is not None else None
        r = dict(absorbed=absorbed, born=b, memory=ms)
        line = f"{name:11} absorbed={absorbed:6.2%}  "
        if b:
            line += f"P={b['P']}  TV={b['tv']:.4f} [{b['tv_lo']:.4f},{b['tv_hi']:.4f}]"
            r["born_pass"] = bool(absorbed >= 0.99 and b["tv_hi"] <= EPS_TV)
            line += f"  Born {'PASS' if r['born_pass'] else 'FAIL'}"
        else:
            r["born_pass"] = False; line += "no records"
        print(line + extra)
        if ms:
            for lab, (m, lo, hi, n) in ms.items():
                print(f"{'':11}   E[s | previous sign {lab}] = {m:+.4f} [{lo:+.4f},{hi:+.4f}]  (n={n})")
        results[name] = r
        return r

    rng = np.random.default_rng(ss[0]); rec, done, mem, _ = run_events(rng, "POS")
    pos = report("POS", rec, done, mem)
    rng = np.random.default_rng(ss[1]); rec, done, psi2 = run_neg(rng)
    neg = report("NEG", rec, done, None, f"   mean final x = {np.round(psi2.mean(0), 3).tolist()}")
    results["NEG"]["mean_final_x"] = psi2.mean(0).tolist()
    for m, si in ((1, 2), (4, 3)):
        rng = np.random.default_rng(ss[si]); rec, done, mem, _ = run_events(rng, "REV", m=m)
        report(f"REV-{m}", rec, done, mem)
    rng = np.random.default_rng(ss[4]); rec, done, mem, _ = run_events(rng, "REV", m=1, shuffle=True)
    report("REV-1-shuf", rec, done, mem)
    rng = np.random.default_rng(ss[5]); rec, done, mem, _, ev = run_cross(rng)
    report("CROSS", rec, done, mem, f"   median events/run = {int(np.median(ev))}")

    rev1 = results["REV-1"]["memory"]
    nb = results["NEG"]["born"]
    neg_ok = nb is not None and nb["tv_lo"] > EPS_TV
    valid = results["POS"]["born_pass"] and neg_ok
    print("\n" + "=" * 100)
    print("DECISION (computed):")
    if not valid and QUICK:
        print("  QUICK mode: controls are underpowered; this is a code check, not a result.")
    elif not valid:
        print("  RUN INVALID: a control failed. No conclusion drawn.")
    print(f"  [{'CONFIRMED' if results['POS']['born_pass'] else 'NOT CONFIRMED'}] P1 POS absorbs and gives Born")
    print(f"  [{'CONFIRMED' if neg_ok else 'NOT CONFIRMED'}] P2 NEG records are not Born (TV_lo > {EPS_TV})")
    p3 = abs(rev1["+1"][0] + 1) < 1e-12 and abs(rev1["-1"][0] - 1) < 1e-12
    print(f"  [{'CONFIRMED' if p3 else 'NOT CONFIRMED'}] P3 REV-1 signs alternate exactly (E[s|s_prev] = -s_prev)")
    print(f"  [{'CONFIRMED' if results['REV-1-shuf']['born_pass'] else 'NOT CONFIRMED'}] P4 REV-1 shuffled gives Born")
    for name in ("REV-1", "REV-4", "CROSS"):
        r = results[name]; mem = r["memory"]
        fair = all(lo <= 0 <= hi for (_, lo, hi, n) in mem.values() if n > 0)
        print(f"  {name:6}: signs conditionally fair? {'yes' if fair else 'NO'};  "
              f"absorbed {r['absorbed']:.1%};  Born {'PASS' if r['born_pass'] else 'FAIL'}")
    print("=" * 100)
    out = here.with_name("carrier_jump_results.json")
    json.dump(dict(sha256=digest, trials=TRIALS, eps=EPS, H=H, valid=bool(valid), results=results),
              open(out, "w"), indent=1, default=float)
    print(f"Wall time {time.time() - t0:.0f} s. Results: {out}")


if __name__ == "__main__":
    main()